// 히라가나 → 가타카나 (유니코드에서 정확히 0x60 만큼 떨어져 있어요)
function toKatakana(str) {
  return str.replace(/[ぁ-ゖ]/g, ch => String.fromCharCode(ch.charCodeAt(0) + 0x60));
}

// 위 표를 프로그램이 쓰기 편한 목록으로 바꿔요.
const KANA = [];          // 모든 글자 목록
const KANA_BY_ID = {};    // 글자로 바로 찾기:  KANA_BY_ID['か']
const KANA_LAYOUT = { h: {}, k: {} };  // 글자표 화면에서 쓸 칸 배치

for (const script of ['h', 'k']) {
  for (const group of Object.keys(KANA_ROWS)) {
    KANA_LAYOUT[script][group] = KANA_ROWS[group].map(row => row.map(cell => {
      if (!cell) return null;
      const [hira, romaji, ko, romAlt = [], koAlt = [], note = ''] = cell;
      const kana = script === 'h' ? hira : toKatakana(hira);
      const item = {
        id: kana, kana, script, group, romaji, ko,
        note: script === 'h' ? note : toKatakana(note),
        romajiAnswers: [romaji, ...romAlt],
        koAnswers: [ko, ...koAlt],
      };
      KANA.push(item);
      KANA_BY_ID[kana] = item;
      return kana;
    }));
  }
}
