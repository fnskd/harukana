// 글자와 실제 소리가 다른 단어 (인사말 끝의 は는 "와"로 읽어요)
const PRON_FIX = { 'こんにちは': 'こんにちわ', 'こんばんは': 'こんばんわ' };

// 위 목록을 프로그램이 쓰기 편한 모양으로 바꿔요.
const VOCAB = [];
const VOCAB_BY_ID = {};
for (const [cat, list] of Object.entries(VOCAB_RAW)) {
  for (const [word, reading, meaning, kr = '', sim = 0] of list) {
    const id = 'w:' + word;
    if (VOCAB_BY_ID[id]) { console.warn('단어가 두 번 있어요:', word); continue; }
    const item = {
      id, word, cat, meaning, kr,
      reading: reading || word,
      pron: PRON_FIX[reading || word] || reading || word,   // 로마자·한글 발음을 만들 때 쓰는 읽기
      hasKanji: !!reading && reading !== word,
      similar: !!sim,
    };
    VOCAB.push(item);
    VOCAB_BY_ID[id] = item;
  }
}

